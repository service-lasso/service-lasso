const reasonSet = new Set(commandValidationReasons);
// Separate finite stderr observation. No private values or exception inspection.
export function observeCommandValidation(index, validate, report = value => process.stderr.write(value)) {
  let first = null, evaluating = null;
  const evaluate = (reason, predicate, rejection) => {
    evaluating = reasonSet.has(reason) ? reason : "command_selector_unavailable";
    const value = predicate();
    if ((rejection ? value : !value) && first === null && reasonSet.has(reason) && reason !== "command_selector_unavailable") first = reason;
    return value;
  };
  const observation = {
    enter: reason => { evaluating = reasonSet.has(reason) ? reason : "command_selector_unavailable"; },
    fail: (reason, predicate) => evaluate(reason, predicate, true),
    pass: (reason, predicate) => evaluate(reason, predicate, false),
    rejected: reason => { if (first === null && reasonSet.has(reason) && reason !== "command_selector_unavailable") first = reason; else if (!reasonSet.has(reason)) evaluating = "command_selector_unavailable"; },
  };
  try { return validate(observation); }
  catch (error) {
    // Reasons originate only from literal source-owned call sites. The command
    // ordinal is selected by the already shape-validated two/three-entry journal.
    const record = {
      schema: "service-lasso.command-validation-failure-observation.v1",
      boundary: "command_native_journal", privateIdentity: "unavailable",
      ...(Number.isInteger(index) && index >= 0 && index <= 2 ? { commandOrdinal: index + 1 } : {}),
      observationStatus: first === null ? "unavailable" : "captured",
      reason: first ?? evaluating ?? "command_selector_unavailable",
    };
    try { report(`[command-validation-failure-observation] ${JSON.stringify(record)}\n`); }
    catch { /* Capture failure never replaces the original refusal. */ }
    throw error;
  }
}
